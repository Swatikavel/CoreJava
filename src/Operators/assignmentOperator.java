package Operators;

public class assignmentOperator {
    public static void main(String[] args) {
// initial value
        int num = 10;
        System.out.println("Initial:" + num);  //10

        //add 5 -> num =num +5
        num = +5;
        // num = num +5
        System.out.println("After +5:" + num);

        // multiply by 2 -> num =num *2
        //* num * = 2;
        System.out.println("After *2:" + num);


    }
}