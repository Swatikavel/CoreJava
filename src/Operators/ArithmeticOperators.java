package Operators;

public class ArithmeticOperators {
    public static void main (String[] args){
        int a =10, b=3;

        // Addition
        int sum =a+b;// 13

        // Subtraction
        int diff = a-b; // 7

        // Multiplication  // 30
        int mul =a*b;

        // Division
        int div = a/b; //  3

        // module
        int mod =a%b; // 1

        System.out.println("Sum: " + sum);
        System.out.println("Difference: " +diff);
        System.out.println("Multiplication: " +mul);
        System.out.println("Division: " +div);
    }

}
